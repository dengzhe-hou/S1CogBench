def _source_parts(row):
    text = row['text']
    spans = list(RESPONSE.finditer(text))
    if not spans or len(spans) != text.count('<<') or len(spans) != text.count('>>'):
        raise ValueError('Every original response marker must parse exactly once.')
    return text, spans, text[:spans[0].start()]


def parse_multiple_cue(row, source_row):
    text, spans, initial = _source_parts(row)
    cue_match = re.search(r'Both Progladine and Amalydine can take five values \(([^)]+)\)\.', initial)
    level_match = re.search(r'Caldionine can take nine values \(([^)]+)\)\.', initial)
    if cue_match is None or level_match is None:
        raise ValueError('Original instructions must enumerate five cues and nine response levels.')
    cue_levels = tuple(cue_match.group(1).split(', '))
    keys = tuple(level_match.group(1).split(', '))
    if len(set(cue_levels)) != 5 or len(set(keys)) != 9:
        raise ValueError('Original cue and response scales must retain all distinct levels.')
    representation = 'numeric' if all(k.isdigit() for k in keys) else 'verbal'
    question = {'type': 'choice',
        'instructions': 'What Caldionine concentration do you estimate for the current individual? Select one of the original nine values.',
        'criteria': {key: f'Estimate the Caldionine concentration as {key}.' for key in keys}}
    trials = []
    for index, span in enumerate(spans):
        prefix, label = text[:span.start()], span.group(1)
        stimulus = re.search(r'(Progladine: ([^.]+)\. Amalydine: ([^.]+)\.) You say that the Caldionine concentration is $', prefix)
        if stimulus is None or label not in keys or any(stimulus.group(i) not in cue_levels for i in (2, 3)):
            raise ValueError('Unrecognized original multiple-cue stimulus or legal response.')
        suffix = text[span.end():].split('\n', 1)[0]
        feedback = re.fullmatch(r'\. That is (correct|incorrect)\. The correct concentration of Caldionine is (?:indeed )?([^.]+)\.', suffix)
        correct = None
        if feedback:
            correct = feedback.group(2)
            if correct not in keys or ((label == correct) != (feedback.group(1) == 'correct')):
                raise ValueError('Multiple-cue feedback contradicts its stated response scale or correctness.')
            phase = 'feedback'
        elif suffix.strip() == '.':
            phase = 'no_feedback'
        else:
            raise ValueError('Unrecognized multiple-cue feedback; do not omit or infer a target.')
        trials.append(CategoryTrial('multiple_cue_judgment', row['experiment'], row['participant'],
            source_row, index, phase, f'caldionine_level_{representation}', index, span.start(),
            prefix, keys, label, correct, question, stimulus.group(1), suffix if feedback else None))
    expected = {'exp1.csv': Counter(feedback=230, no_feedback=50),
                'exp2.csv': Counter(feedback=230, no_feedback=50),
                'exp3.csv': Counter(feedback=138)}[row['experiment'].rsplit('/', 1)[1]]
    if Counter(t.phase for t in trials) != expected:
        raise ValueError('The complete original multiple-cue session/feedback phases were not parsed.')
    return trials


def parse_multi_attribute(row, source_row):
    text, spans, initial = _source_parts(row)
    key_match = re.search(r'two options, labeled ([A-Z]) and ([A-Z])\.', initial)
    validity_match = re.search(r'validities of (\d+)%, (\d+)%, (\d+)%, and (\d+)%', initial)
    if key_match is None or validity_match is None or key_match.group(1) == key_match.group(2):
        raise ValueError('Original product keys and expert validity order must be visible.')
    keys = key_match.groups()
    question = {'type': 'choice',
        'instructions': 'Which of the current two products do you choose as superior in quality?',
        'criteria': {key: f'Choose product {key}.' for key in keys}}
    trials = []
    for index, span in enumerate(spans):
        prefix, label = text[:span.start()], span.group(1)
        stimulus = re.search(r'(Product ([A-Z]) ratings: \[([01] [01] [01] [01])\]\. Product ([A-Z]) ratings: \[([01] [01] [01] [01])\]\.) You press $', prefix)
        if stimulus is None or (stimulus.group(2), stimulus.group(4)) != keys or label not in keys:
            raise ValueError('Unrecognized original product ratings, product order or response.')
        if text[span.end():].split('\n', 1)[0] != '.':
            raise ValueError('Unexpected multi-attribute feedback; original source has no realized-quality labels.')
        trials.append(CategoryTrial('multi_attribute_choice', row['experiment'], row['participant'],
            source_row, index, 'choice', 'product_choice', index, span.start(), prefix,
            keys, label, None, question, stimulus.group(1), None))
    if len(trials) != 96:
        raise ValueError('The complete original 96-response multi-attribute session was not parsed.')
    return trials


def load_trials(task, source=DEFAULT_SOURCE):
    parser = {'multiple_cue_judgment': parse_multiple_cue,
              'multi_attribute_choice': parse_multi_attribute}[task]
    trials = []
    with Path(source).open() as stream:
        for source_row, line in enumerate(stream):
            row = json.loads(line)
            if row['experiment'] in TASK_SOURCES[task]:
                trials.extend(parser(row, source_row))
    if not trials:
        raise ValueError('No complete task sessions found in the supplied official held-out source.')
    return trials


def score(trial, prediction):
    row = score_prediction(trial, prediction)
    if trial.correct_category is None:
        row['category_correct_under_human_history'] = None
    row['native_rating_absolute_error'] = None
    if trial.task == 'multiple_cue_judgment':
        cue_levels = re.search(r'Both Progladine and Amalydine can take five values \(([^)]+)\)\.', trial.state).group(1).split(', ')
        cue_values = re.fullmatch(r'Progladine: ([^.]+)\. Amalydine: ([^.]+)\.', trial.stimulus).groups()
        row['cue_values_in_original_order'] = list(cue_values)
        row['cue_ranks_in_original_order'] = [cue_levels.index(value) + 1 for value in cue_values]
        row['cue_representation'] = 'numeric' if all(value.isdigit() for value in cue_levels) else 'verbal'
        row['response_representation'] = trial.response_kind.removeprefix('caldionine_level_')
        row['native_rating_error_unit'] = 'Steps on the ordered original nine-level response scale (0 to 8).'
        row['original_human_response_rank'] = trial.output_keys.index(trial.original_choice_label) + 1
        row['response_scale'] = list(trial.output_keys)
        row['objective_rank_absolute_error'] = None
        if not row['invalid_response']:
            selected_rank = trial.output_keys.index(row['choice']) + 1
            row['selected_response_rank'] = selected_rank
            row['native_rating_absolute_error'] = abs(selected_rank - row['original_human_response_rank'])
            row['objective_rank_absolute_error'] = (abs(selected_rank - (trial.output_keys.index(trial.correct_category) + 1))
                if trial.correct_category is not None else None)
        row['objective_target_semantics'] = 'Source-provided feedback only; missing during original no-feedback phase.'
    else:
        products = re.findall(r'Product ([A-Z]) ratings: \[([01] [01] [01] [01])\]', trial.stimulus)
        row['expert_ratings_by_product'] = {key: [int(value) for value in values.split()] for key, values in products}
        row['expert_validities_in_original_order'] = [int(value) / 100 for value in re.search(
            r'validities of (\d+)%, (\d+)%, (\d+)%, and (\d+)%', trial.state).groups()]
        row['objective_target_semantics'] = 'No observed realized-quality label; human choice is not an objective outcome.'
    return row
